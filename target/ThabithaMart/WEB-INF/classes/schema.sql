CREATE TABLE IF NOT EXISTS users(
 id BIGINT AUTO_INCREMENT PRIMARY KEY, username VARCHAR(80) UNIQUE NOT NULL,
 password_hash VARCHAR(100) NOT NULL, role VARCHAR(20) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS products(
 id BIGINT AUTO_INCREMENT PRIMARY KEY, seller_id BIGINT NOT NULL,
 name VARCHAR(150) NOT NULL, description VARCHAR(1000), price DECIMAL(10,2) NOT NULL,
 stock INT NOT NULL, category VARCHAR(60) NOT NULL, image_url VARCHAR(500),
 active BOOLEAN DEFAULT TRUE, FOREIGN KEY(seller_id) REFERENCES users(id));
CREATE TABLE IF NOT EXISTS orders(
 id BIGINT AUTO_INCREMENT PRIMARY KEY, buyer_id BIGINT NOT NULL,
 status VARCHAR(30) NOT NULL, total DECIMAL(10,2) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(buyer_id) REFERENCES users(id));
CREATE TABLE IF NOT EXISTS order_items(
 id BIGINT AUTO_INCREMENT PRIMARY KEY, order_id BIGINT NOT NULL, product_id BIGINT NOT NULL,
 seller_id BIGINT NOT NULL, quantity INT NOT NULL, unit_price DECIMAL(10,2) NOT NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id), FOREIGN KEY(product_id) REFERENCES products(id));
CREATE TABLE IF NOT EXISTS reviews(
 id BIGINT AUTO_INCREMENT PRIMARY KEY, product_id BIGINT NOT NULL, buyer_id BIGINT NOT NULL,
 stars INT NOT NULL, review_text VARCHAR(1000), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(product_id,buyer_id));
